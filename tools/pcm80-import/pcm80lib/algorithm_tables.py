"""Patchable Parameter Information tables for all 10 PCM80 base
algorithms, transcribed from the MIDI Implementation Details manual
(pages 22-23, 35-48).

dest_number is auto-assigned (sequential count of real fields within a
dest_list_id, 0-indexed - flags don't consume a dest_number, and
dest_list_id resets the counter, matching the manual's own documented
behavior) rather than hand-transcribed, removing a whole class of
transcription-arithmetic risk. Only bit width, group/label text, and
range-decode id need to be transcribed per field.
"""

FLD = object()
FLAG = "flag"


def build(spec, dlid0_start=0):
    """spec: list of ('F', bits, dlid, group, label, rd) | 'T' (tempo flag).
    Auto-assigns dest_number per dlid."""
    counters = {}
    out = []
    for item in spec:
        if item == "T":
            out.append(("flag",))
            continue
        _, bits, dlid, group, label, rd = item
        dn = counters.get(dlid, 0)
        counters[dlid] = dn + 1
        out.append(("field", bits, dlid, dn, group, label, rd))
    return out


def Fx(bits, dlid, group, label, rd):
    return ("F", bits, dlid, group, label, rd)


